"""Generate native DSP metadata and controller profiles from one source of truth."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def generate(root=ROOT):
    root=Path(root);rows=json.loads((root/'app/native_effects_data.json').read_text());code=[]
    def number(v):return str(float(v))+'f'
    for row in rows:
        assert len(row['parameters'])<=32
        code.append(f'inline static constexpr std::array<Port,{len(row["parameters"])}> {row["id"]}_ports{{{{')
        for p in row['parameters']:
            code.append('    {'+','.join((json.dumps(p['symbol']),json.dumps(p['name']),number(p['min']),number(p['max']),number(p['default']),'true' if p.get('log') else 'false','true' if p.get('integer') else 'false'))+'},')
        code.append('}};')
        profile=dict(schema=1,id='native-'+row['id'],uri=row['uri'],title=row['name'],provider='native-core',parameters=[dict(p,index=i) for i,p in enumerate(row['parameters'])],pages=row['pages'],overrides={p['symbol']:{k:v for k,v in p.items() if k not in ('symbol','min','max','default')} for p in row['parameters']})
        assert all(len(p['controls'])<=8 for p in profile['pages'])
        assert {v for p in profile['pages'] for v in p['controls']}=={p['symbol'] for p in row['parameters']}
        (root/'app/plugin_profiles_data'/('native-'+row['id']+'.json')).write_text(json.dumps(profile,indent=2)+'\n')
    code.append('inline static constexpr std::array<Spec,12> specs{{')
    for r in rows:code.append('    {'+','.join((json.dumps(r['id']),json.dumps(r['uri']),json.dumps(r['name']),r['id']+'_ports.data()',str(len(r['parameters']))))+'},')
    code.append('}};')
    (root/'src/audio/native_effect_specs.inc').write_text('// Generated by tools/generate_native_effects.py; edit app/native_effects_data.json.\n'+'\n'.join(code)+'\n')
if __name__=='__main__':generate()
